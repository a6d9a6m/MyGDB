def article_page(
    *,
    article: dict[str, Any],
    content_html: str,
    toc_html: str,
    related: list[dict[str, Any]],
    previous_article: dict[str, Any] | None,
    next_article: dict[str, Any] | None,
    has_body: bool,
) -> str:
    source_url = article.get("content_source_url") or article.get("url") or "#"
    fetched = article.get("content_fetched_at")
    status = "" if has_body else '<div class="content-state">正文尚未入库。当前展示的是分析摘要；后续抓取原文后将自动渲染为长文阅读页。</div>'
    fetched_html = f'<div><span>原文入库</span><strong>{h(format_date(fetched))}</strong></div>' if fetched else ""
    related_html = "".join(mini_card(item) for item in related)
    previous_html = f'<a href="{h(previous_article["href"])}">上一篇：{h(previous_article.get("title"))}</a>' if previous_article else "<span></span>"
    next_html = f'<a href="{h(next_article["href"])}">下一篇：{h(next_article.get("title"))}</a>' if next_article else "<span></span>"
    body = f"""
{site_header(active="", prefix="../")}
<nav class="article-topbar" aria-label="Article">
  <a href="../library.html">返回资料库</a>
  <a href="{h(source_url)}" target="_blank" rel="noopener noreferrer">打开原文</a>
</nav>
<main class="reader">
  <header class="reader-header">
    <div class="reader-kicker">
      <span class="score">{score_text(article.get('relevance_score'))}</span>
      <span class="source-pill">{h(article.get('source'))}</span>
      {tag_html(article.get('tags', [])[:5], link_base='../library.html')}
    </div>
    <h1>{h(article.get('title'))}</h1>
    <p class="summary-lede">{h(article.get('summary'))}</p>
    <div class="reader-meta">
      <div><span>采集</span><strong>{h(format_date(article.get('collected_at', '')))}</strong></div>
      <div><span>分析</span><strong>{h(format_date(article.get('analyzed_at', '')))}</strong></div>
      <div><span>归档</span><strong>{h(format_date(article.get('organized_at', '')))}</strong></div>
      {fetched_html}
    </div>
    {status}
  </header>
  {toc_html}
  <article class="prose">{content_html}</article>
  <section class="related">
    <div class="section-title"><div><span class="eyebrow">相关阅读</span><h2>同标签条目</h2></div><span>{len(related)} 篇</span></div>
    <div class="related-grid">{related_html}</div>
  </section>
  <nav class="article-nav">{previous_html}{next_html}</nav>
</main>
{site_footer()}
"""
    return base_page(title=f"{article.get('title')} - MyGK_DB", body=body, stylesheet="../assets/styles.css", body_class="article")


def search_data_script(articles: list[dict[str, Any]]) -> str:
    payload = [
        {
            "id": article.get("id", ""),
            "title": article.get("title", ""),
            "summary": article.get("summary", ""),
            "source": article.get("source", ""),
            "tags": article.get("tags", []),
            "relevance_score": article.get("relevance_score", 0),
            "organized_at": article.get("organized_at", ""),
            "href": article.get("href", ""),
        }
        for article in articles
    ]
    return "window.MYGK_SEARCH_DATA = " + json.dumps(payload, ensure_ascii=False) + ";"
