"""HTML templates for the static knowledge-base site."""

from __future__ import annotations

import json
from html import escape
from typing import Any
from urllib.parse import quote


def h(value: Any) -> str:
    return escape(str(value or ""), quote=True)


def format_date(value: str) -> str:
    if not value:
        return ""
    return value.split("T", 1)[0]


def score_text(value: Any) -> str:
    try:
        return f"{float(value):.2f}"
    except (TypeError, ValueError):
        return "0.00"


def query_link(page: str, key: str, value: str) -> str:
    return f"{page}?{key}={quote(value)}"


def tag_html(tags: list[str], *, link_base: str | None = None) -> str:
    parts: list[str] = []
    for tag in tags:
        if link_base:
            href = query_link(link_base, "tag", tag)
            parts.append(f'<a class="tag" href="{h(href)}">{h(tag)}</a>')
        else:
            parts.append(f'<span class="tag">{h(tag)}</span>')
    return "".join(parts)


def meta_row(article: dict[str, Any], *, link_base: str | None = None) -> str:
    source = str(article.get("source") or "")
    source_html = f'<span class="source-pill">{h(source)}</span>'
    if link_base and source:
        source_html = f'<a class="source-pill" href="{h(query_link(link_base, "source", source))}">{h(source)}</a>'
    return (
        '<div class="meta-row">'
        f'<span class="score">{score_text(article.get("relevance_score"))}</span>'
        f"{source_html}"
        f'<span>{h(format_date(article.get("organized_at", "")))}</span>'
        "</div>"
    )


def article_card(article: dict[str, Any], *, compact: bool = False) -> str:
    summary = "" if compact else f"<p>{h(article.get('summary'))}</p>"
    return f"""
<article class="article-card" data-article-card="{h(article['id'])}">
  <a class="article-card-main" href="{h(article['href'])}">
    {meta_row(article)}
    <h3>{h(article.get('title'))}</h3>
    {summary}
  </a>
  <div class="meta-row tag-row">{tag_html(article.get('tags', [])[:4], link_base='library.html')}</div>
</article>
"""


def mini_card(article: dict[str, Any]) -> str:
    return f"""
<a class="mini-card" href="{h(article['href'])}">
  {meta_row(article)}
  <h3>{h(article.get('title'))}</h3>
</a>
"""


def latest_item(article: dict[str, Any]) -> str:
    return f"""
<article class="latest-item">
  <div>{meta_row(article)}</div>
  <a href="{h(article['href'])}"><h3>{h(article.get('title'))}</h3></a>
  <p>{h(article.get('summary'))}</p>
</article>
"""


def option_list(values: list[str], label: str) -> str:
    options = [f'<option value="all">{h(label)}</option>']
    options.extend(f'<option value="{h(value)}">{h(value)}</option>' for value in values)
    return "\n".join(options)


def base_page(*, title: str, body: str, stylesheet: str = "assets/styles.css", body_class: str = "") -> str:
    class_attr = f' class="{h(body_class)}"' if body_class else ""
    return f"""<!doctype html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{h(title)}</title>
  <link rel="stylesheet" href="{h(stylesheet)}">
</head>
<body{class_attr}>
  <div class="site-shell">
    {body}
  </div>
</body>
</html>
"""


def site_header(*, active: str, prefix: str = "") -> str:
    home_active = ' aria-current="page"' if active == "home" else ""
    library_active = ' aria-current="page"' if active == "library" else ""
    return f"""
<header class="site-header">
  <a class="site-mark" href="{h(prefix)}index.html">MyGK_DB</a>
  <nav class="site-nav" aria-label="Primary">
    <a href="{h(prefix)}index.html"{home_active}>首页</a>
    <a href="{h(prefix)}library.html"{library_active}>资料库</a>
  </nav>
</header>
"""


def site_footer() -> str:
    return '<footer class="site-footer">Generated by MyGK_DB static site builder.</footer>'


def index_page(
    *,
    articles: list[dict[str, Any]],
    tags: list[str],
    sources: list[str],
    last_updated: str,
) -> str:
    featured = articles[0] if articles else None
    side = articles[1:4]
    latest = articles[4:10] if len(articles) > 4 else articles[1:7]
    top_tags = tags[:8]

    featured_html = ""
    if featured:
        featured_html = f"""
<section class="feature-grid" aria-label="精选文章">
  <a class="feature-card" href="{h(featured['href'])}">
    <span class="eyebrow">本期精选</span>
    {meta_row(featured)}
    <h2>{h(featured.get('title'))}</h2>
    <p>{h(featured.get('summary'))}</p>
  </a>
  <div class="feature-side">
    {''.join(mini_card(article) for article in side)}
  </div>
</section>
"""

    latest_html = "".join(latest_item(article) for article in latest)
    tag_links = tag_html(top_tags, link_base="library.html")
    source_links = "".join(
        f'<a class="quiet-link" href="{h(query_link("library.html", "source", source))}">{h(source)}</a>'
        for source in sources[:4]
    )

    body = f"""
{site_header(active="home")}
<main>
  <section class="hero">
    <div class="hero-copy">
      <span class="eyebrow">AI / LLM / Agent 技术情报</span>
      <h1>一座为长期阅读整理的 AI 知识库</h1>
      <p>从 GitHub、RSS 等来源沉淀高质量条目。首页只保留少量精选，完整搜索、标签和来源筛选放在资料库页面。</p>
      <div class="hero-actions">
        <a class="button" href="library.html">进入资料库</a>
        <a class="button secondary" href="#latest">查看最新</a>
      </div>
    </div>
    <dl class="summary-panel">
      <div><dt>文章</dt><dd>{len(articles)}</dd></div>
      <div><dt>标签</dt><dd>{len(tags)}</dd></div>
      <div><dt>来源</dt><dd>{len(sources)}</dd></div>
      <div><dt>更新</dt><dd>{h(format_date(last_updated))}</dd></div>
    </dl>
  </section>
  <section class="page-section">
    {featured_html}
  </section>
  <section class="page-section topic-entry" aria-label="快速入口">
    <div>
      <span class="eyebrow">快速进入</span>
      <h2>按主题或来源继续浏览</h2>
    </div>
    <div class="topic-groups">
      <div class="tag-row">{tag_links}</div>
      <div class="source-row">{source_links}</div>
    </div>
  </section>
  <section class="page-section" id="latest">
    <div class="section-title">
      <div>
        <span class="eyebrow">最新整理</span>
        <h2>最近 6 篇</h2>
      </div>
      <a class="text-link" href="library.html">查看全部 {len(articles)} 篇</a>
    </div>
    <div class="latest-list">{latest_html}</div>
  </section>
</main>
{site_footer()}
"""
    return base_page(title="MyGK_DB Knowledge", body=body, body_class="home-page")


